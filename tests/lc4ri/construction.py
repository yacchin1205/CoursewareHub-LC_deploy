"""Human operations and independent acceptance checks for construction notebooks."""
import json
import os
import re
import shlex
import subprocess

from notebook_ui import source


def remote(address, command):
    return subprocess.check_output(['ssh', *shlex.split(os.environ['ANSIBLE_SSH_ARGS']),
        'centos@' + address, 'sudo -- ' + command], text=True, timeout=180).strip()


def operate(key, original, args, run, edit, select, state, page, records, results):
    if key == 'D03':
        before = {host: remote(host, 'cat /proc/sys/kernel/random/boot_id') for host in (args.master, args.worker)}
    for index, cell in enumerate(original['cells']):
        text = source(cell)
        if cell['cell_type'] != 'code' or not text.strip():
            continue
        # These are the same inventory/group input fields used in D01 and D02.
        if "hosts_file = './cwhtest0001_inventory'" in text:
            edit(index, text.replace('cwhtest0001', 'ci_lc4ri'), 'Select the inventory generated by D02')
        if key == 'D05' and text.startswith('lti_config = {}') and args.saml is None:
            from moodle_fixture import running_moodle
            subprocess.run(['docker','network','create','cwh-lc4ri-moodle'],check=True)
            args.moodle = args.fixtures.enter_context(running_moodle('172.30.77.1', 'cwh-lc4ri-moodle', results / 'moodle-platform'))
            m = args.moodle
            edit(index, text + '\nmoodle_lti_config(lti_config, ' + repr(m.url) + ', ' + repr(m.metadata['client_id']) + ', ' + repr(m.metadata['deployment_id']) + ')', 'Enter the registered Moodle LTI tool parameters')
        if key == 'D05' and args.saml is not None and (text.startswith('# msg_stdout') and 'cgidp_metadata' in text or text.startswith('# !ls -l {cgidp_metadata}') or text.startswith('# !ansible') and 'src={cgidp_metadata}' in text):
            edit(index,'\n'.join(line.removeprefix('# ') for line in text.splitlines()),'Enable the documented IdP metadata import using the supplied fixture file')
        if key == 'D05' and "teacher_email = 'nakagawa@carabiner.jp'" in text:
            edit(index, text.replace('nakagawa@carabiner.jp', 'ciadmin@example.test'), 'Enter the test administrator email')
        if 'use_saml_cert_as_server_cert = False' in text:
            edit(index, text.replace('= False', '= True'), 'Use the locally provisioned test certificate')
        # The notebook explicitly asks the operator to confirm and Freeze these cells.
        if text.strip().endswith('assert False'):
            if key == 'D04':
                for host in (args.master, args.worker):
                    remote(host, 'systemctl is-active docker')
                    remote(host, 'docker compose version')
            elif key == 'D05' and '証明書' in text:
                remote(args.master, 'openssl x509 -in /home/centos/certs/coursewarehub.test.cer -noout -subject')
            elif key == 'D05' and 'アドレス' in text:
                assert 'ciadmin@example.test' in state(index - 1)['text']
            else:
                raise AssertionError('Unrecognized manual confirmation: ' + text)
            select(index)
            page.locator('button:has(.fa-freeze)').click()
            assert state(index)['frozen']
            records.append(dict(notebook=key, cell=index, action='confirm prerequisites and Freeze via toolbar'))
            continue
        if 'docker stack rm coursewarehub' in text:
            lines = text.splitlines()
            removed = next(i for i,line in enumerate(lines) if 'docker stack rm coursewarehub' in line)
            wait = """import time
for wait_attempt in range(90):
    remaining_services = !ansible -b -a 'docker service ls --filter label=com.docker.stack.namespace=coursewarehub -q' {target_hub} -l {target_group}
    if not any(line.strip() for line in remaining_services[1:]):
        break
    time.sleep(2)
else:
    raise TimeoutError('CoursewareHub stack removal did not complete')"""
            lines.insert(removed + 1, wait)
            edit(index, '\n'.join(lines), 'Wait for asynchronous stack removal before the next deployment')
        if key == 'D05' and text.strip() == 'time.sleep(60)':
            wait = """import requests
for wait_attempt in range(120):
    try:
        ready = requests.get('http://HOST:8000/hub/health', timeout=5)
        if ready.status_code == 200:
            break
    except requests.RequestException:
        pass
    time.sleep(2)
else:
    raise TimeoutError('CoursewareHub did not become ready')""".replace('HOST', args.master)
            edit(index, wait, 'Wait for the actual Hub to initialize before continuing')
        inputs = ()
        if 'swarm_token = input()' in text:
            token = remote(args.master, 'docker swarm join-token worker -q')
            inputs = ('docker swarm join --token ' + token + ' ' + args.master + ':2377',)
        elif 'db_pass = getpass()' in text:
            inputs = (os.environ['LC4RI_DB_PASSWORD'],)
        elif "acme_server = input(" in text:
            inputs = ('', '', '', 'ciadmin@example.test', 'rsa')
        if key == 'D05' and text.startswith('# !ansible') and 'docker pull {singleuser_image}' in text:
            edit(index, text.removeprefix('# '), 'Choose the documented option to pull the initial course image')
        observed = run(index, inputs=inputs)
        output = json.dumps(observed['outputs'], ensure_ascii=False)
        if key == 'D05' and 'teacher_info_stdout =' in text and not getattr(args, 'admin_password', None):
            combined = '\n'.join(o.get('text', '') for o in observed['outputs'])
            combined = re.sub(r'\x1b\[[0-?]*[ -/]*[@-~]', '', combined)
            credential = re.search(r'ciadmin@example\.test\s+(\S+)', combined)
            assert credential, 'The original user creation cell did not return an administrator password'
            args.admin_password = credential.group(1)

        # Inspect Ansible results even when shell status is explicitly ignored.
        dry_run = '-CD' in text or '-Cv' in text or '-CDv' in text
        diagnostic = key == 'D05' and ("id {teacher_id}" in text or 'id {teacher_uid}' in text)
        if not dry_run and not diagnostic and re.search(r'FAILED!|UNREACHABLE!|failed=[1-9]|SQLSTATE\[|psql:[^\n]*ERROR:|ERROR:  relation', output):
            raise AssertionError(f'{key} cell {index}: Ansible operation failed: {output[-3000:]}')
    if key == 'D03':
        after = {host: remote(host, 'cat /proc/sys/kernel/random/boot_id') for host in before}
        assert before[args.worker] != after[args.worker], 'D03 did not reboot the worker OS'
        mounts = remote(args.worker, 'findmnt --json --target /exchange')
        assert 'nfs' in mounts and args.master in mounts, mounts
        remote(args.master, "sh -c 'echo lc4ri-nfs > /exchange/lc4ri-proof'")
        assert remote(args.worker, 'cat /exchange/lc4ri-proof') == 'lc4ri-nfs'
        (results / 'nfs-reboot.json').write_text(json.dumps(dict(before=before, after=after, mounts=json.loads(mounts)), indent=2))
    elif key == 'D04':
        nodes = remote(args.master, "docker node ls --format '{{.Status}} {{.Availability}}'")
        assert nodes.splitlines().count('Ready Active') == 2, nodes
        (results / 'swarm-nodes.txt').write_text(nodes)
        dns = remote(args.master, 'docker run --rm busybox:1.37 nslookup -type=A coursewarehub.test')
        assert args.master in dns, dns
        (results / 'deployment-dns.txt').write_text(dns)


def check_runtime(args, results, browser, *, after_update=False):
    from guest import Guest
    manager = Guest('master', args.master, 'ssh')
    if args.saml is not None:
        from saml_provider import prepare_saml
        prepare_saml(args.saml,manager,results/'saml')
    elif not after_update:
        from custom_image import running_repository
        args.build_repository=args.fixtures.enter_context(running_repository(os.environ['LC4RI_GATEWAY']))
    from runtime_ui import check
    check(args, results, browser, after_update=after_update)
    if args.saml is not None:
        from saml_provider import check_saml
        check_saml(results/'saml',args.saml,args.teacher_username,browser)
        return
    from moodle_ui import check_moodle
    args.moodle.register_tool_key(manager)
    if not after_update:
        tasks = manager.output(['docker','service','ps','coursewarehub_auth-proxy','--filter','desired-state=running','-q']).splitlines()
        assert len(tasks) == 1
        task = json.loads(manager.output(['docker','inspect',tasks[0]]))[0]
        container = task['Status']['ContainerStatus']['ContainerID']
        manager.run(['docker','exec',container,'php','/var/www/bin/add-local-user.php','cistudent@example.test'])
        args.student_username = manager.output(['docker','exec',container,'php','-r', "require '/var/www/lib/functions.php'; echo get_username_from_mail_address('cistudent@example.test');"])
    check_moodle(results / 'moodle', args.moodle, manager,
        {'teacher':args.teacher_username,'student':args.student_username},
        browser, expected_existing=after_update,repository=args.build_repository)
